"""Demo data for a fresh clone: one user, groups, checks in every state, a public status page,
and 30 days of past data so charts and uptime % aren't empty.

    docker compose run --rm seed

Runs once: if the demo user exists, it changes nothing. History is generated by simulating
every run, so rollups, raw results (last 24 h) and incidents agree. Past incidents get no
outbox rows: seeding sends no email. Checks point at the emulator; Payments and Staging web
point at failing endpoints, so they go down live after seeding (Staging inside a
maintenance window, so its DOWN email waits for the window to end).
"""

