@dataclass
class Outage:
    ago: timedelta  # start, before now
    lasts: timedelta
    kind: ErrorKind
    message: str
    status: int | None = None


@dataclass
class Demo:
    name: str
    path: str
    group: str | None
    interval_s: int
    base_ms: int  # typical response time
    expected_body: str | None = None
    timeout_s: int = 10
    paused_ago: timedelta | None = None
    outages: list[Outage] = field(default_factory=list[Outage])
    page_name: str | None = None  # shown on the public status page under this name


def _502(ago: timedelta, lasts: timedelta) -> Outage:
    return Outage(ago, lasts, ErrorKind.STATUS_MISMATCH, "expected status 200, got 502", status=502)


