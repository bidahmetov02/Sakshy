@dataclass
class Run:
    at: datetime
    ok: bool
    response_ms: int | None
    status: int | None
    kind: ErrorKind | None = None
    message: str | None = None
    is_retry: bool = False


@dataclass
class History:
    runs: list[Run] = field(default_factory=list[Run])
    incidents: list[dict[str, Any]] = field(default_factory=list[dict[str, Any]])


def simulate(demo: Demo, now: datetime, rng: random.Random) -> History:
    """Every run from 30 days ago to now (or to the pause), with the state machine's retries:
    a failure is re-checked RETRY_DELAY apart until FAIL_THRESHOLD confirms the incident."""
    history = History()
    interval = timedelta(seconds=demo.interval_s)
    end = now - demo.paused_ago if demo.paused_ago else now
    at = now - HISTORY + timedelta(seconds=rng.uniform(0, demo.interval_s))
    open_incident: dict[str, Any] | None = None
    while at < end:
        outage = next((o for o in demo.outages if now - o.ago <= at < now - o.ago + o.lasts), None)
        if outage is None:
            ms = round(demo.base_ms * rng.uniform(0.7, 1.4) * (4 if rng.random() < 0.02 else 1))
            history.runs.append(Run(at, True, ms, 200))
            if open_incident is not None:
                open_incident["ended_at"] = at
                open_incident = None
        else:
            has_response = outage.status is not None
            fail = Run(
                at,
                False,
                round(demo.base_ms * rng.uniform(0.7, 1.4)) if has_response else None,
                outage.status,
                outage.kind,
                outage.message,
            )
            history.runs.append(fail)
            if open_incident is None:
                retries = [
                    replace(fail, at=at + RETRY_DELAY * n, is_retry=True)
                    for n in range(1, FAIL_THRESHOLD)
                ]
                history.runs += retries
                open_incident = {
                    "started_at": at,
                    "detected_at": retries[-1].at,
                    "ended_at": None,
                    "cause_kind": outage.kind,
                    "cause_message": outage.message,
                }
                history.incidents.append(open_incident)
        at += interval
    return history


def rollups(check_id: int, runs: list[Run]) -> list[dict[str, Any]]:
    """Hourly rollups as the worker builds them: retries not counted."""
    hours: dict[datetime, list[Run]] = defaultdict(list)
    for run in runs:
        if not run.is_retry:
            hours[run.at.replace(minute=0, second=0, microsecond=0)].append(run)
    rows: list[dict[str, Any]] = []
    for bucket, hour in hours.items():
        times = [r.response_ms for r in hour if r.response_ms is not None]
        rows.append(
            {
                "check_id": check_id,
                "bucket": bucket,
                "total": len(hour),
                "ok": sum(r.ok for r in hour),
                "rt_count": len(times),
                "rt_sum_ms": sum(times),
                "rt_min_ms": min(times, default=None),
                "rt_max_ms": max(times, default=None),
            }
        )
    return rows


async def ensure_partitions(now: datetime) -> None:
    """Raw results reach back to yesterday: create its partition (the worker's housekeeping
    creates today's and the week ahead), or those rows would sit in the default one."""
    engine = create_engine(str(get_settings().database_url))
    try:
        await housekeeping.run(engine, get_settings().rollup_retention_days)
        day = (now - RAW_HISTORY).date()
        name = housekeeping.partition_name(day)
        async with engine.begin() as conn:
            await conn.execute(
                text(
                    f"CREATE TABLE IF NOT EXISTS {name} PARTITION OF check_results"
                    f" FOR VALUES FROM ('{day} 00:00+00') TO ('{day + timedelta(days=1)} 00:00+00')"
                )
            )
    finally:
        await engine.dispose()


async def seed(conn: AsyncConnection, now: datetime) -> None:
    rng = random.Random(42)  # noqa: S311 (the same demo every time; not security)
    created = now - HISTORY
    user_id = (
        await conn.execute(
            insert(User)
            .values(email=EMAIL, password_hash=await hash_password(PASSWORD), created_at=created)
            .returning(User.id)
        )
    ).scalar_one()

    group_ids: dict[str, int] = {}
    for name, emails in GROUPS.items():
        group_ids[name] = (
            await conn.execute(
                insert(CheckGroup)
                .values(owner_id=user_id, name=name, alert_emails=emails, created_at=created)
                .returning(CheckGroup.id)
            )
        ).scalar_one()

    page_id = (
        await conn.execute(
            insert(StatusPage)
            .values(
                owner_id=user_id,
                slug="demo",
                title="Example Inc. status",
                show_response_times=True,
                show_uptime=True,
                show_incidents=True,
                created_at=created,
            )
            .returning(StatusPage.id)
        )
    ).scalar_one()

    position = 0
    for demo in CHECKS:
        check_id = (
            await conn.execute(
                insert(Check)
                .values(
                    owner_id=user_id,
                    group_id=group_ids[demo.group] if demo.group else None,
                    name=demo.name,
                    url=EMULATOR + demo.path,
                    interval_s=demo.interval_s,
                    timeout_s=demo.timeout_s,
                    expected_body=demo.expected_body,
                    alert_emails=[EMAIL],
                    is_paused=demo.paused_ago is not None,
                    created_at=created,
                    updated_at=now - demo.paused_ago if demo.paused_ago else created,
                )
                .returning(Check.id)
            )
        ).scalar_one()

        history = simulate(demo, now, rng)
        for incident in history.incidents:
            ended = incident["ended_at"] is not None
            await conn.execute(
                insert(Incident).values(
                    check_id=check_id,
                    **incident,
                    end_reason=IncidentEndReason.RECOVERED if ended else None,
                    down_alert_queued=True,
                )
            )
        if rows := rollups(check_id, history.runs):
            await conn.execute(insert(CheckStatsHourly), rows)
        recent = [
            {
                "check_id": check_id,
                "checked_at": r.at,
                "ok": r.ok,
                "response_ms": r.response_ms,
                "status_code": r.status,
                "error_kind": r.kind,
                "error_message": r.message,
                "is_retry": r.is_retry,
            }
            for r in history.runs
            if r.at >= now - RAW_HISTORY
        ]
        if recent:
            await conn.execute(insert(CheckResult), recent)

        last = history.runs[-1]
        next_run = last.at + timedelta(seconds=demo.interval_s)
        last_change = max((i["ended_at"] for i in history.incidents), default=created)
        await conn.execute(
            insert(CheckState).values(
                check_id=check_id,
                # Paused: a fresh start on resume. Active: due one interval after its last run.
                next_run_at=now if demo.paused_ago else next_run,
                state=MonitorState.PENDING if demo.paused_ago else MonitorState.UP,
                state_changed_at=now - demo.paused_ago if demo.paused_ago else last_change,
                last_checked_at=last.at,
                last_ok=last.ok,
                last_status_code=last.status,
                last_response_ms=last.response_ms,
            )
        )

        if demo.page_name:
            await conn.execute(
                insert(StatusPageItem).values(
                    owner_id=user_id,
                    status_page_id=page_id,
                    check_id=check_id,
                    display_name=demo.page_name,
                    position=position,
                )
            )
            position += 1

    await conn.execute(
        insert(MaintenanceWindow).values(
            owner_id=user_id,
            group_id=group_ids["Staging"],
            starts_at=now - timedelta(minutes=30),
            ends_at=now + timedelta(hours=2),
            reason="Staging redeploy",
        )
    )


async def main() -> None:
    settings = get_settings()
    engine = create_engine(str(settings.database_url))
    try:
        async with engine.begin() as conn:
            now: datetime = (await conn.execute(select(func.now()))).scalar_one()
            exists = await conn.scalar(select(User.id).where(func.lower(User.email) == EMAIL))
        if exists:
            print(f"Already seeded: log in as {EMAIL} / {PASSWORD}")
            return
        await ensure_partitions(now.astimezone(UTC))
        async with engine.begin() as conn:
            await seed(conn, now.astimezone(UTC))
    finally:
        await engine.dispose()
    print(
        f"Seeded. Log in at {settings.app_base_url} as {EMAIL} / {PASSWORD}\n"
        f"Public status page: {settings.app_base_url}/status/demo"
    )


if __name__ == "__main__":
    asyncio.run(main())
